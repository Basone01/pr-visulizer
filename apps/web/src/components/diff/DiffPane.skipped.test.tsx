import type { ChangedFile, ChangedFileFacts } from "@pr-visulizer/shared"
import { QueryClient, QueryClientProvider } from "@tanstack/react-query"
import { act, render, screen } from "@testing-library/react"
import userEvent from "@testing-library/user-event"
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"

import { buildAnchorIndex } from "@/utils/diff/anchors"

import type { PrTarget } from "@/entity/pr"

import { NoPatchAvailableError } from "@/service/prClient"

import { usePeekNavigation } from "@/hooks/usePeekNavigation"

import { DiffPane } from "./DiffPane"
import { NO_COMMIT_RANGE, activeCommitRange } from "./diffPaneTestProps"

// The diff pane's states (CONTRACT §11.1, L6'): a generated file, a diff too large, a diff that
// could not be read, and a load that failed. Each ends in a designed state, never in an
// endless "Loading diff…".

const getPatch = vi.hoisted(() => vi.fn<(target: unknown, path: string) => Promise<string>>())

vi.mock("@/service/clientFactory", async () => {
  const { createMemoryKeyValueStore } = await import("@/utils/storage/keyValueStore")
  const store = createMemoryKeyValueStore()
  const client = { getPatch }

  return { getPrClient: () => client, getAppStorage: () => store }
})

vi.mock("@/hooks/useLineTokenizer", () => ({
  useLineTokenizer: () => (lineText: string) => [{ content: lineText, cssVar: "var(--text)" }],
}))

// The Rust `repo_file_diff` cap crosses the invoke boundary as this bare string (lib.rs).
const NATIVE_CAP_REFUSAL = "git diff exceeded the bounded patch byte limit"

const PATCH = ["@@ -1 +1 @@", "-.a{color:red}", "+.a{color:blue}"].join("\n")

const target: PrTarget = { owner: "acme", repo: "webapp", number: 42 }

function changedFile(path: string): ChangedFile {
  return { path, status: "modified", additions: 1, deletions: 1, language: null }
}

type HarnessProps = {
  file: ChangedFile
  fileFacts?: ChangedFileFacts | null
  commitRange?: typeof NO_COMMIT_RANGE
}

function DiffPaneHarness({ file, fileFacts = null, commitRange = NO_COMMIT_RANGE }: HarnessProps) {
  const nav = usePeekNavigation("")

  return (
    <DiffPane
      changedPaths={new Set<string>()}
      target={target}
      file={file}
      symbols={[]}
      anchorIndex={buildAnchorIndex([], [])}
      nav={nav}
      reviewed={false}
      onToggleReviewed={() => {}}
      suggestedNextPath={null}
      onOpenFile={() => {}}
      onHide={() => {}}
      drafts={[]}
      onAddDraft={() => {}}
      onUpdateDraft={() => {}}
      onDeleteDraft={() => {}}
      commitRange={commitRange}
      fileFacts={fileFacts}
    />
  )
}

function renderPane(props: HarnessProps) {
  const queryClient = new QueryClient()

  return render(
    <QueryClientProvider client={queryClient}>
      <DiffPaneHarness {...props} />
    </QueryClientProvider>
  )
}

function buttonNames(): string[] {
  return screen.queryAllByRole("button").map((button) => button.textContent ?? "")
}

beforeEach(() => {
  getPatch.mockReset()
})

afterEach(() => {
  vi.useRealTimers()
})

describe("DiffPane for a generated file", () => {
  it("shows a file generated by its name at once, without reading its patch", async () => {
    // Arrange
    const generatedFile = changedFile("assets/build/css/summary_css.css.map")
    getPatch.mockResolvedValue(PATCH)

    // Act
    renderPane({ file: generatedFile })
    const notice = await screen.findByRole("status")

    // Assert
    const expected = { title: true, showAnyway: true, patchReads: 0 }
    expect({
      title: notice.textContent?.includes("Generated file, not shown"),
      showAnyway: buttonNames().includes("Show diff anyway"),
      patchReads: getPatch.mock.calls.length,
    }).toEqual(expected)
  })

  it("follows the analysis: a file it found generated by shape is shown as generated without a read", async () => {
    // Arrange
    const path = "assets/build/css/message_css.css"
    const analysisFacts: ChangedFileFacts = {
      skip: { path, reason: "generated" },
      diffOmission: null,
    }
    getPatch.mockResolvedValue(PATCH)

    // Act
    renderPane({ file: changedFile(path), fileFacts: analysisFacts })
    const notice = await screen.findByRole("status")

    // Assert
    const expected = { generated: true, patchReads: 0 }
    expect({
      generated: notice.textContent?.includes("Generated file, not shown"),
      patchReads: getPatch.mock.calls.length,
    }).toEqual(expected)
  })

  it("Show diff anyway loads the diff of a generated file and moves focus to it", async () => {
    // Arrange
    const generatedFile = changedFile("assets/build/css/top_user.css.map")
    getPatch.mockResolvedValue(PATCH)
    renderPane({ file: generatedFile })
    const showAnyway = await screen.findByRole("button", { name: "Show diff anyway" })

    // Act
    await userEvent.click(showAnyway)

    // Assert
    const expected = { diffShown: true, focusInPane: true }
    expect({
      diffShown: (await screen.findByText(".a{color:blue}")) !== null,
      focusInPane: document.activeElement !== document.body,
    }).toEqual(expected)
  })
})

describe("DiffPane for a file whose diff is omitted", () => {
  it("says a hand-written file over the cap is still part of the review, with Open on GitHub and no futile Show anyway or Retry", async () => {
    // Arrange
    const routerFile = changedFile("src/server/router.ts")
    getPatch.mockRejectedValue(NATIVE_CAP_REFUSAL)

    // Act
    renderPane({ file: routerFile })
    const notice = await screen.findByRole("status")

    // Assert
    const expected = {
      title: true,
      stillInReview: true,
      limit: true,
      buttons: ["Open on GitHub"],
    }
    expect({
      title: notice.textContent?.includes("Diff too large to show"),
      stillInReview: notice.textContent?.includes("still part of the review"),
      limit: notice.textContent?.includes("128 KiB limit"),
      buttons: buttonNames().filter((name) =>
        ["Open on GitHub", "Show diff anyway", "Retry"].includes(name)
      ),
    }).toEqual(expected)
  })

  it("shows a patch GitHub omits (API mode) as too large, never as an error with a futile Retry", async () => {
    // Arrange
    const hugeCss = changedFile("src/styles/all.css")
    getPatch.mockRejectedValue(new NoPatchAvailableError(hugeCss.path))

    // Act
    renderPane({ file: hugeCss })
    const notice = await screen.findByRole("status")

    // Assert
    const expected = { tooLarge: true, retry: false }
    expect({
      tooLarge: notice.textContent?.includes("Diff too large to show"),
      retry: buttonNames().includes("Retry"),
    }).toEqual(expected)
  })

  it("shows the reader's own message for a diff that could not be read, with no Retry", async () => {
    // Arrange
    const legacyFile = changedFile("legacy/report.php")
    const notUtf8 = "git diff was not valid UTF-8"
    getPatch.mockRejectedValue(notUtf8)

    // Act
    renderPane({ file: legacyFile })
    const notice = await screen.findByRole("status")

    // Assert
    const expected = { message: true, retry: false }
    expect({
      message: notice.textContent?.includes(`Its diff could not be read: ${notUtf8}`),
      retry: buttonNames().includes("Retry"),
    }).toEqual(expected)
  })
})

describe("DiffPane under a commit range", () => {
  it("shows a range file whose patch GitHub omitted as too large, never an endless Loading diff", async () => {
    // Arrange
    const path = "src/server/router.ts"
    const commitRange = activeCommitRange({
      rangeDiff: {
        baseSha: "aaaaaaa",
        headSha: "bbbbbbb",
        truncated: false,
        files: [
          {
            path,
            status: "modified",
            additions: 4000,
            deletions: 3900,
            patch: null,
            previousPath: null,
          },
        ],
      },
    })

    // Act
    renderPane({ file: changedFile(path), commitRange })
    const title = await screen.findByText("Diff too large to show")

    // Assert
    const expected = { tooLarge: true, loading: false }
    expect({
      tooLarge: title !== null,
      loading: screen.queryByText("Loading diff…") !== null,
    }).toEqual(expected)
  })
})

describe("DiffPane when a patch fails to load", () => {
  it("shows an error with the message and Retry after a failure that may pass, and Retry loads the diff", async () => {
    // Arrange
    vi.useFakeTimers({ shouldAdvanceTime: true })
    const file = changedFile("src/app.css")
    const networkDrop = new TypeError("Failed to fetch")
    getPatch.mockRejectedValueOnce(networkDrop).mockRejectedValueOnce(networkDrop)
    getPatch.mockRejectedValueOnce(networkDrop).mockRejectedValueOnce(networkDrop)
    getPatch.mockResolvedValue(PATCH)
    renderPane({ file })
    await act(async () => {
      await vi.advanceTimersByTimeAsync(10_000)
    })
    const alert = await screen.findByRole("alert")
    const shownError = alert.textContent

    // Act
    await userEvent.click(screen.getByRole("button", { name: "Retry" }))

    // Assert
    const expected = { errorShown: true, diffAfterRetry: true }
    expect({
      errorShown:
        shownError?.includes("Couldn't load this diff") && shownError.includes("Failed to fetch"),
      diffAfterRetry: (await screen.findByText(".a{color:blue}")) !== null,
    }).toEqual(expected)
  })
})
