import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { describe, expect, it } from "vitest"

import { NATIVE_PATCH_BYTE_LIMIT, type PatchEvidence, classifyChangedFile } from "../src/index.js"

// A normal hand-written patch: short lines, under the cap.
const NORMAL_PATCH: PatchEvidence = {
  kind: "patch",
  patch: ["@@ -1,2 +1,2 @@", " package main", "-func a() {}", "+func a() { return }"].join("\n"),
}

describe("which changed files are generated", () => {
  it("never calls hand-written source generated because of a folder or file name alone", () => {
    // Arrange
    const sourcePaths = [
      "cmd/build/main.go",
      "src/build/index.ts",
      "scripts/build",
      "app/Vendor/Order.php",
      "internal/vendor/x.go",
      "src/generated/handwritten.ts",
    ]

    // Act
    const skips = sourcePaths.map((path) => classifyChangedFile(path, NORMAL_PATCH).skip)

    // Assert
    expect(skips).toEqual(sourcePaths.map(() => null))
  })

  it("matches build folders on folder names only, in lower case, even when the patch is over the cap", () => {
    // Arrange
    const overCap: PatchEvidence = { kind: "over-cap" }
    const handWrittenPaths = ["scripts/build", "app/Vendor/Order.php", "tools/Dist/index.ts"]

    // Act
    const skips = handWrittenPaths.map((path) => classifyChangedFile(path, overCap).skip)

    // Assert
    expect(skips).toEqual(handWrittenPaths.map(() => null))
  })

  it("calls a file generated by its name, or by a build folder together with machine-made shape", () => {
    // Arrange
    const oneLongLine: PatchEvidence = {
      kind: "patch",
      patch: `@@ -1 +1 @@\n-.a{}\n+${".a{color:red}".repeat(4_000)}`,
    }
    const cases: Array<[string, PatchEvidence]> = [
      ["assets/build/css/app.css.map", { kind: "not-read" }],
      ["public/js/app.min.js", { kind: "not-read" }],
      ["web/node_modules/left-pad/index.js", { kind: "not-read" }],
      ["assets/build/css/app.css", oneLongLine],
      ["assets/build/css/message_css.css", { kind: "over-cap" }],
      ["dist/bundle.css", { kind: "omitted-by-github" }],
    ]

    // Act
    const reasons = cases.map(
      ([path, evidence]) => classifyChangedFile(path, evidence).skip?.reason
    )

    // Assert
    expect(reasons).toEqual(cases.map(() => "generated"))
  })

  it("keeps a hand-written file whose patch is over the cap in the review, with only its diff omitted", () => {
    // Arrange
    const path = "src/server/router.ts"
    const overCap: PatchEvidence = { kind: "over-cap" }

    // Act
    const facts = classifyChangedFile(path, overCap)

    // Assert
    const expected = {
      skip: null,
      diffOmission: { path, part: "diff", reason: "too-large", limitBytes: 131072 },
    }
    expect(facts).toEqual(expected)
  })

  it("records any other patch failure as an unreadable diff with the reader's message", () => {
    // Arrange
    const path = "legacy/report.php"
    const notUtf8: PatchEvidence = { kind: "unreadable", message: "git diff was not valid UTF-8" }

    // Act
    const facts = classifyChangedFile(path, notUtf8)

    // Assert
    const expected = {
      skip: null,
      diffOmission: {
        path,
        part: "diff",
        reason: "unreadable",
        message: "git diff was not valid UTF-8",
      },
    }
    expect(facts).toEqual(expected)
  })
})

describe("the too-large limit", () => {
  it("is the same number as the desktop's native diff cap", () => {
    // Arrange
    const rustSourcePath = fileURLToPath(
      new URL("../../../apps/desktop/src-tauri/src/lib.rs", import.meta.url)
    )
    const rustSource = readFileSync(rustSourcePath, "utf8")

    // Act
    const rustCap = /const MAX_REPO_FILE_DIFF_BYTES: usize = (\d+) \* (\d+);/.exec(rustSource)
    const rustCapBytes = rustCap ? Number(rustCap[1]) * Number(rustCap[2]) : null

    // Assert
    expect(rustCapBytes).toBe(NATIVE_PATCH_BYTE_LIMIT)
  })
})
